import time
from datetime import datetime

import requests


class FbrApiService:
    DEFAULT_ENDPOINTS = {
        "sandbox": {
            "post": "https://gw.fbr.gov.pk/di_data/v1/di/postinvoicedata_sb",
            "validate": "https://gw.fbr.gov.pk/di_data/v1/di/validateinvoicedata_sb",
        },
        "production": {
            "post": "https://gw.fbr.gov.pk/di_data/v1/di/postinvoicedata",
            "validate": "https://gw.fbr.gov.pk/di_data/v1/di/validateinvoicedata",
        },
    }

    def __init__(self, env):
        self.env = env

    def _endpoint_for(self, config, operation="post"):
        if config.connection_mode in ("sandbox", "production"):
            configured = (config.sandbox_url if config.connection_mode == "sandbox" else config.production_url) or ""
            configured = configured.rstrip("/")
            if configured:
                if operation == "validate" and "postinvoicedata" in configured:
                    return configured.replace("postinvoicedata_sb", "validateinvoicedata_sb").replace(
                        "postinvoicedata", "validateinvoicedata"
                    )
                if operation == "post" and "validateinvoicedata" in configured:
                    return configured.replace("validateinvoicedata_sb", "postinvoicedata_sb").replace(
                        "validateinvoicedata", "postinvoicedata"
                    )
                if "postinvoicedata" in configured or "validateinvoicedata" in configured:
                    return configured
            return self.DEFAULT_ENDPOINTS[config.connection_mode][operation]
        return "mock://fbr-digital-invoicing"

    def _mock_success(self, move, payload, started):
        number = f"DI-TEST-{move.id}-{datetime.utcnow().strftime('%Y%m%d%H%M%S')}"
        qr_data = {
            "fbr_invoice_number": number,
            "odoo_invoice": move.name,
            "seller_ntn": payload["seller"].get("ntn"),
            "buyer": payload["buyer"].get("name"),
            "amount_total": payload["invoice"].get("amount_total"),
        }
        return {
            "success": True,
            "fbr_invoice_number": number,
            "qr_code": qr_data,
            "raw_response": {"mock": True, "status": "accepted", "invoice_number": number},
            "error_code": False,
            "error_message": False,
            "http_status": 200,
            "duration_ms": int((time.monotonic() - started) * 1000),
            "endpoint": "mock://fbr-digital-invoicing",
            "is_mock": True,
        }

    def _mock_failure(self, started):
        return {
            "success": False,
            "fbr_invoice_number": False,
            "qr_code": False,
            "raw_response": {"mock": True, "status": "rejected", "code": "MOCK_VALIDATION_ERROR"},
            "error_code": "MOCK_VALIDATION_ERROR",
            "error_message": "Mock FBR failure generated by Bashalog demo mode.",
            "http_status": 422,
            "duration_ms": int((time.monotonic() - started) * 1000),
            "endpoint": "mock://fbr-digital-invoicing",
            "is_mock": True,
        }

    def _extract_validation_response(self, raw):
        if not isinstance(raw, dict):
            return {}
        return raw.get("validationResponse") or {}

    def _extract_invoice_number(self, raw):
        if not isinstance(raw, dict):
            return False
        if raw.get("invoiceNumber"):
            return raw.get("invoiceNumber")
        validation = self._extract_validation_response(raw)
        for invoice_status in validation.get("invoiceStatuses") or []:
            if invoice_status.get("invoiceNo"):
                return invoice_status.get("invoiceNo")
        return False

    def _is_valid_fbr_response(self, raw):
        if not isinstance(raw, dict):
            return False
        validation = self._extract_validation_response(raw)
        if not validation:
            return False
        if str(validation.get("statusCode", "")).strip() != "00":
            return False
        if (validation.get("status") or "").strip().lower() not in ("", "valid"):
            return False
        for invoice_status in validation.get("invoiceStatuses") or []:
            if str(invoice_status.get("statusCode", "")).strip() != "00":
                return False
            if (invoice_status.get("status") or "").strip().lower() not in ("", "valid"):
                return False
        return True

    def _extract_error_details(self, raw, http_status):
        if isinstance(raw, dict):
            validation = self._extract_validation_response(raw)
            for invoice_status in validation.get("invoiceStatuses") or []:
                if invoice_status.get("errorCode") or invoice_status.get("error"):
                    return (
                        invoice_status.get("errorCode") or validation.get("errorCode") or "FBR_VALIDATION_ERROR",
                        invoice_status.get("error") or validation.get("error") or "FBR validation failed.",
                    )
            if validation.get("errorCode") or validation.get("error"):
                return (
                    validation.get("errorCode") or "FBR_VALIDATION_ERROR",
                    validation.get("error") or validation.get("status") or "FBR validation failed.",
                )
            if raw.get("errorCode") or raw.get("error") or raw.get("message"):
                return (
                    raw.get("errorCode") or "FBR_HTTP_ERROR",
                    raw.get("error") or raw.get("message") or f"FBR returned HTTP {http_status}",
                )
        return ("FBR_HTTP_ERROR", f"FBR returned HTTP {http_status}")

    def _request(self, config, payload, started, operation):
        endpoint = self._endpoint_for(config, operation=operation)
        headers = {
            "Authorization": f"Bearer {config.api_token}",
            "Content-Type": "application/json",
            "Accept": "application/json",
        }
        try:
            response = requests.post(endpoint, json=payload, headers=headers, timeout=config.timeout_seconds or 30)
            try:
                raw = response.json()
            except ValueError:
                raw = response.text
            success = 200 <= response.status_code < 300 and self._is_valid_fbr_response(raw)
            invoice_number = self._extract_invoice_number(raw)
            qr_code = raw.get("qrCode") if isinstance(raw, dict) else False
            error_code, error_message = (False, False) if success else self._extract_error_details(raw, response.status_code)
            return {
                "success": success,
                "fbr_invoice_number": invoice_number if success else False,
                "qr_code": qr_code,
                "raw_response": raw,
                "error_code": error_code,
                "error_message": error_message,
                "http_status": response.status_code,
                "duration_ms": int((time.monotonic() - started) * 1000),
                "endpoint": endpoint,
                "is_mock": False,
                "sent_payload": payload,
            }
        except requests.RequestException as exc:
            return {
                "success": False,
                "fbr_invoice_number": False,
                "qr_code": False,
                "raw_response": str(exc),
                "error_code": "API_TIMEOUT" if "timeout" in str(exc).lower() else "API_ERROR",
                "error_message": str(exc),
                "http_status": False,
                "duration_ms": int((time.monotonic() - started) * 1000),
                "endpoint": endpoint,
                "is_mock": False,
                "sent_payload": payload,
            }

    def submit(self, move, payload, config):
        started = time.monotonic()
        if config.connection_mode == "mock_success":
            result = self._mock_success(move, payload, started)
            result["sent_payload"] = payload
            return result
        if config.connection_mode == "mock_failure":
            result = self._mock_failure(started)
            result["sent_payload"] = payload
            return result
        return self._request(config, payload, started, operation="post")

    def validate(self, move, payload, config):
        started = time.monotonic()
        if config.connection_mode == "mock_success":
            result = self._mock_success(move, payload, started)
            result["sent_payload"] = payload
            return result
        if config.connection_mode == "mock_failure":
            result = self._mock_failure(started)
            result["sent_payload"] = payload
            return result
        return self._request(config, payload, started, operation="validate")
